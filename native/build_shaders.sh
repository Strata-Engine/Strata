#!/bin/sh
# Assemble and compile the GLSL in shaders/ to SPIR-V and embed it in
# strata_shaders.h. The header is checked in, so consumers need no shader
# compiler.
#
# A shader's source has no #version line: one is put in front of it together
# with the shared files it is listed with here (ubo.glsl first, always).
cd "$(dirname "$0")" || exit 1
TMP="${TMPDIR:-/tmp}/strata-shaders.$$"; mkdir -p "$TMP"; trap 'rm -rf "$TMP"' EXIT
OUT="$TMP/all.h"
echo "/* Generated by build_shaders.sh from the GLSL in shaders. Do not edit. */" > "$OUT"
echo "#include <stdint.h>" >> "$OUT"
build_named() { # generated symbol, file, then shared files
  name="$1"; f="$2"; shift 2
  {
    echo "#version 460"
    if [ "$name" = strata_quad_batch_vert ]; then echo "#define STRATA_BATCHED_QUADS"; fi
    if [ "$name" = strata_collide_comp ]; then echo "#define STRATA_TRACE_WORLD_ONLY"; fi
    cat shaders/ubo.glsl
    for inc in "$@"; do cat "shaders/$inc"; done
    cat "shaders/$f"
  } > "$TMP/$f"
  glslangValidator -V --vn "$name" -o "$TMP/$f.h" "$TMP/$f" > "$TMP/log" 2>&1 || { cat "$TMP/log"; exit 1; }
  sed 's/^const uint32_t/static const uint32_t/' "$TMP/$f.h" >> "$OUT"
}
build() { # file, then the shared files to put in front of it
  build_named "strata_$(echo "$1" | tr '.' '_')" "$@"
}
build cull.comp
build collide.comp fx.glsl tiles.glsl trace.glsl
build quad.vert
build_named strata_quad_batch_vert quad.vert
build cross.vert
build loose.vert
build figure.vert figquad.glsl
build figure_shadow.vert figquad.glsl
build fullscreen.vert
build gbuffer.frag tiles.glsl
build gather.frag shade.glsl tiles.glsl gbuf.glsl trace.glsl sky.glsl
build light.frag shade.glsl tiles.glsl gbuf.glsl trace.glsl sky.glsl reflect.glsl
build composite.frag
build water.frag shade.glsl tiles.glsl gbuf.glsl trace.glsl sky.glsl reflect.glsl
build particle.vert fx.glsl tiles.glsl trace.glsl sky.glsl
build particle.frag fx.glsl tiles.glsl trace.glsl sky.glsl
build ui.vert
build ui.frag tiles.glsl
build overlay.vert
build overlay.frag
cp "$OUT" strata_shaders.h
# strata_vk.c carries a stamp of the header, so a shader-only change still
# changes the C source forge looks at
stamp=$(shasum strata_shaders.h | cut -c1-16)
sed -i '' "s/^#define STRATA_SHADERS_STAMP .*/#define STRATA_SHADERS_STAMP \"$stamp\"/" strata_vk.c
