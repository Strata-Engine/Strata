#!/bin/sh
# Compile the GLSL in shaders/ to SPIR-V and embed it in strata_shaders.h.
# The header is checked in, so consumers need no shader compiler.
cd "$(dirname "$0")" || exit 1
glslangValidator -V --vn strata_quad_vert -o shaders/quad_vert.h shaders/quad.vert || exit 1
glslangValidator -V --vn strata_quad_frag -o shaders/quad_frag.h shaders/quad.frag || exit 1
glslangValidator -V --vn strata_cull_comp -o shaders/cull_comp.h shaders/cull.comp || exit 1
glslangValidator -V --vn strata_cross_vert -o shaders/cross_vert.h shaders/cross.vert || exit 1
{ echo "/* Generated by build_shaders.sh from the GLSL in shaders. Do not edit. */"
  echo "#include <stdint.h>"
  sed 's/^const uint32_t/static const uint32_t/' shaders/quad_vert.h
  sed 's/^const uint32_t/static const uint32_t/' shaders/quad_frag.h
  sed 's/^const uint32_t/static const uint32_t/' shaders/cull_comp.h
  sed 's/^const uint32_t/static const uint32_t/' shaders/cross_vert.h
} > strata_shaders.h
rm shaders/quad_vert.h shaders/quad_frag.h shaders/cull_comp.h shaders/cross_vert.h
